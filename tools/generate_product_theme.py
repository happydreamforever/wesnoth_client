#!/usr/bin/env python3
"""Generate the native and Android theme constants from one public descriptor."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = 'tools/native-account-game/ui-theme.json'
OUTPUTS = ('alliance_game/product_theme.hpp', 'tools/native-account-game/ProductTheme.java')
COLORS = ('gold', 'ivory', 'stone', 'teal_shadow', 'ink', 'parchment', 'light_gold', 'dark_gold')


def load_theme(repo):
    def unique(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ValueError('Duplicate interface theme field.')
            result[key] = value
        return result
    raw = (Path(repo) / SOURCE).read_bytes()
    if len(raw) > 16384:
        raise ValueError('Interface theme is oversized.')
    value = json.loads(raw, object_pairs_hook=unique)
    if (not isinstance(value, dict) or set(value) != {'format', 'background', 'title_kicker', 'title_name', 'font', 'body_font', 'palette'}
            or type(value['format']) is not int or value['format'] != 1):
        raise ValueError('Invalid interface theme fields.')
    if not isinstance(value['background'], str) or not re.fullmatch(r'alliance-ui/[a-z0-9_-]+/[a-z0-9_-]+\.(?:png|webp)', value['background']):
        raise ValueError('Invalid interface background path.')
    for name in ('title_kicker', 'title_name'):
        if not isinstance(value[name], str) or not re.fullmatch(r'[A-Z][A-Z ]{0,39}', value[name]):
            raise ValueError('Invalid interface title.')
    for key, filename in (('font', 'Akademie Alte.ttf'), ('body_font', 'Lato-Regular.ttf')):
        font = value[key]
        if (not isinstance(font, dict) or set(font) != {'asset', 'source', 'bytes', 'sha256'}
                or font['asset'] != 'startup/' + filename or font['source'] != 'fonts/' + filename
                or type(font['bytes']) is not int or not 0 < font['bytes'] <= 1024 * 1024
                or not isinstance(font['sha256'], str) or not re.fullmatch(r'[0-9a-f]{64}', font['sha256'])):
            raise ValueError('Invalid pinned interface font.')
    palette = value['palette']
    if (not isinstance(palette, dict) or set(palette) != set(COLORS)
            or any(not isinstance(palette[name], str) or not re.fullmatch(r'#[0-9A-F]{6}', palette[name]) for name in COLORS)):
        raise ValueError('Invalid interface palette.')
    return value


def generated(repo):
    theme = load_theme(repo)
    canonical = json.dumps(theme, sort_keys=True, separators=(',', ':')).encode('ascii')
    digest = hashlib.sha256(canonical).hexdigest()
    native = ['// SPDX-License-Identifier: GPL-2.0-or-later',
              '// Generated by tools/generate_product_theme.py; edit ui-theme.json.',
              '#pragma once', '#include <cstdint>', 'namespace alliance_game::product_theme {']
    java = ['package org.wesnoth.offline;', '',
            '// Generated by tools/generate_product_theme.py; edit ui-theme.json.',
            'final class ProductTheme {', '    private ProductTheme() {}']
    strings = {'background_asset': theme['background'], 'title_kicker': theme['title_kicker'],
               'title_name': theme['title_name'], 'title_font_asset': theme['font']['asset'],
               'title_font_family': 'Akademie Alte', 'body_font_asset': theme['body_font']['asset'],
               'body_font_family': 'sans', 'descriptor_sha256': digest}
    for name, value in strings.items():
        native.append(f'inline constexpr const char* {name} = {json.dumps(value)};')
        java.append(f'    static final String {name.upper()} = {json.dumps(value)};')
    for name in COLORS:
        color = theme['palette'][name][1:]
        rgb = tuple(int(color[offset:offset + 2], 16) for offset in (0, 2, 4))
        native.append(f'inline constexpr const char* {name}_rgba = "{rgb[0]},{rgb[1]},{rgb[2]},255";')
        native.append(f'inline constexpr std::uint32_t {name}_rgb = 0x{color}u;')
        java.append(f'    static final int {name.upper()} = 0xFF{color};')
    native.append('}')
    java.append('}')
    return {OUTPUTS[0]: ('\n'.join(native) + '\n').encode('ascii'),
            OUTPUTS[1]: ('\n'.join(java) + '\n').encode('ascii')}


def verify_generated(repo):
    for name, expected in generated(repo).items():
        if (Path(repo) / name).read_bytes() != expected:
            raise ValueError('Generated interface theme differs from its descriptor: ' + name)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.check:
        verify_generated(ROOT)
    else:
        for name, data in generated(ROOT).items():
            (ROOT / name).write_bytes(data)
    print('INTERFACE THEME ' + ('VERIFIED' if args.check else 'GENERATED'))


if __name__ == '__main__':
    main()
