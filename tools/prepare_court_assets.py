#!/usr/bin/env python3
"""Verify the supplied map bundle and deterministically prepare public UI assets.

No illustrative ownership, flags, neighbours or source scripts are imported.
The one documented legacy directory alias is explicit, never a fuzzy lookup.
"""
import argparse, hashlib, json
from pathlib import Path

ALIAS = 'Area_A001_64_Castles/'
ASSETS = (
 ('World_128_Areas/Shattered_Crown_Compact_Terrain_Clean_v6.png', 'world.png'),
 ('Area_64_Castles/Verdant_Marches_Asian_Terrain_Clean_v6.png', 'area.png'),
)
def digest(raw): return {'bytes': len(raw), 'sha256': hashlib.sha256(raw).hexdigest()}
def encode(value): return (json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True)+'\n').encode()
def prepare(source, repo):
    manifest=json.loads((source/'MANIFEST.json').read_text())
    if len(manifest['files']) != 27: raise ValueError('Expected all 27 supplied map files.')
    checked=[]
    for entry in manifest['files']:
        name=entry['path']; actual=name.replace(ALIAS,'Area_64_Castles/',1) if name.startswith(ALIAS) else name
        if '..' in Path(actual).parts or Path(actual).is_absolute(): raise ValueError('Unsafe source path')
        path=source/actual
        if path.is_symlink() or not path.is_file(): raise ValueError('Missing ordinary map file: '+actual)
        raw=path.read_bytes()
        if digest(raw) != {key:entry[key] for key in ('bytes','sha256')}: raise ValueError('Source map hash differs: '+actual)
        checked.append({'path':actual,**digest(raw)})
    world=json.loads((source/'World_128_Areas/Shattered_Crown_128_Area_Hex_Coordinates_v6.json').read_text())
    area=json.loads((source/'Area_64_Castles/Verdant_Marches_64_Castles_Hex_Coordinates_v6.json').read_text())
    def nodes(items,w,h,castle=False):
        result=[]
        for i,item in enumerate(items,1):
            expected=f'A001-C{i:03}' if castle else f'A{i:03}'
            if item['id'] != expected or len(item['polygon_pixels']) != 6: raise ValueError('Unordered map coordinates')
            result.append({'id':f'C{i:03}' if castle else expected,'name':item['name'],
                'x':item['x']/w,'y':item['y']/h,
                'polygon':[[p['x']/w,p['y']/h] for p in item['polygon_pixels']]})
        return result
    geometry={'format':1,'world':nodes(world['areas'],3072,2048),
              'castle_template':nodes(area['locations'],3344,1882,True)}
    if len(geometry['world'])!=128 or len(geometry['castle_template'])!=64: raise ValueError('Wrong node count')
    dest=repo/'tools/native-account-game/ui-assets/court';dest.mkdir(parents=True,exist_ok=True)
    generated={name:(source/path).read_bytes() for path,name in ASSETS};generated['geometry.json']=encode(geometry)
    for name,raw in generated.items(): (dest/name).write_bytes(raw)
    ui_manifest=repo/'tools/native-account-game/ui-assets.json';ui=json.loads(ui_manifest.read_text())
    ui['files']=[e for e in ui['files'] if not e['path'].startswith('court/')]
    ui['files'] += [{'path':'court/'+name,**digest(raw)} for name,raw in sorted(generated.items())]
    ui_manifest.write_bytes(encode(ui))
    # Compile geometry into the native client. Its hash is also bound to the APK
    # manifest, and the generator validates identical output in tests.
    lines=['// Generated by tools/prepare_court_assets.py; do not edit.','#pragma once',
           '#include <array>','namespace alliance_game::court_map {',
           'struct Node { const char* id; const char* name; double x,y; std::array<Point,6> polygon; };']
    for key,name in [('world','world_nodes'),('castle_template','castle_nodes')]:
        lines.append(f'inline constexpr std::array<Node,{len(geometry[key])}> {name}{{{{')
        for item in geometry[key]:
            poly=','.join('{'+f'{x:.10f},{y:.10f}'+'}' for x,y in item['polygon'])
            lines.append('{'+json.dumps(item['id'])+','+json.dumps(item['name'])+f',{item["x"]:.10f},{item["y"]:.10f},'+ '{{'+poly+'}}},')
        lines.append('}};')
    lines.append('}')
    (repo/'alliance_game/court_geometry.hpp').write_text('\n'.join(lines)+'\n')
    (repo/'alliance_game/court_assets/source-verification.json').write_bytes(encode({'format':1,'source_files':checked,'packaged':ui['files'][-3:]}))
    print('COURT MAP INPUTS VERIFIED: 27; public assets: 3; world areas: 128; shared castle template: 64')
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--source',type=Path,required=True);p.add_argument('--repo',type=Path,default=Path(__file__).resolve().parents[1]);a=p.parse_args();prepare(a.source,a.repo)
