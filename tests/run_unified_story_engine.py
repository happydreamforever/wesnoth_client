#!/usr/bin/env python3
"""Run the actual singleplayer engine fixture with its account HTTP boundary stubbed.

Build tests/story_engine_probe.cpp into the pinned native engine, replacing the
four sources generated by engine_overlay.py (campaign, attack, advancement and
Lua unit) and linking hero_catalog.cpp/story_progression.cpp. Pass that fixture
executable below. The supplied game data is read only; this script creates an
isolated scenario, private records, real saves and replay evidence in --output.
"""
from pathlib import Path
import os,subprocess,re,json,gzip,hashlib,argparse
parser=argparse.ArgumentParser();parser.add_argument('--engine',type=Path,required=True);parser.add_argument('--game-data',type=Path,required=True);parser.add_argument('--output',type=Path,required=True);args=parser.parse_args()
root=args.output.resolve();root.mkdir(exist_ok=False,parents=True);game=args.game_data.resolve();engine=args.engine.resolve();base_env=os.environ.copy();base_env.update(SDL_VIDEODRIVER='dummy',SDL_AUDIODRIVER='dummy',XDG_CACHE_HOME=str(root/'font-cache'))
data=root/'story-data'
if not data.exists():
 data.mkdir();(data/'data').mkdir();(data/'data/campaigns').mkdir()
 for p in game.iterdir():
  if p.name!='data':(data/p.name).symlink_to(p)
 for p in (game/'data').iterdir():
  if p.name!='campaigns':(data/'data'/p.name).symlink_to(p)
 for p in (game/'data/campaigns').iterdir():
  if p.name!='Two_Brothers':(data/'data/campaigns'/p.name).symlink_to(p)
 (data/'data/campaigns/Two_Brothers').mkdir()
for p in (game/'data/campaigns/Two_Brothers').iterdir():
 if p.name!='_main.cfg' and not (data/'data/campaigns/Two_Brothers'/p.name).exists():(data/'data/campaigns/Two_Brothers'/p.name).symlink_to(p)
plugin=root/'story-exit.lua';plugin.write_text("return function(events,context,info) local played=false while true do if info.name=='titlescreen' and not played then played=true; context.play_campaign{} elseif info.name=='Campaign Selection' then local level=info.find_level{id='Two_Brothers'}; context.select_level{index=level.index}; context.create{} elseif info.name=='Campaign Configure' then context.launch{} elseif info.name=='Game' then played=true; if info.can_move().can_move and info.current_turn().current_turn==1 then context.save_game{filename='StoryMid'}; context.end_turn{} end elseif info.name=='titlescreen' and played then context.exit{code=0} elseif info.name=='Dialog' then played=true; context.skip_dialog{} end events,context,info=wesnoth.plugin.next_slice() end end")
reload_plugin=root/'story-reload.lua';reload_plugin.write_text(plugin.read_text().replace("local played=false", "local played=false; local titles=0").replace("if info.name=='titlescreen' and not played then played=true; context.play_campaign{} elseif ", "if info.name=='titlescreen' and not played then titles=titles+1; if titles>=3 then context.exit{code=0} end elseif "))
results=[]
def cmd(label,args,env,allowed=(0,)):
 
 try:p=subprocess.run([str(a) for a in args],env=env,text=True,stdout=subprocess.PIPE,stderr=subprocess.STDOUT,timeout=90)
 except subprocess.TimeoutExpired as e:
  (root/(label+'.log')).write_bytes(e.stdout or b'');raise
 (root/(label+'.log')).write_text(p.stdout)
 if p.returncode not in allowed:raise RuntimeError(label+' failed '+str(p.returncode)+' '+p.stdout[-1500:])
 return p.stdout
for index,variant in enumerate(['win','dead','loss']):
 profile=root/('profile-'+variant);profile.mkdir(exist_ok=False);env=base_env.copy();env['WESNOTH_ALLIANCE_PROFILE']=str(profile/'alliance-public-profile.json')
 addon=root/('story-addon-'+variant)
 cmd('story-generate-'+variant,[engine,'--generate-story',addon,variant],env)
 wml=(addon/'_main.cfg').read_text();wml=re.sub(r'code="((?:""|[^"])*)"',lambda m:'code=<<'+m.group(1).replace('""','"')+'>>',wml)
 wml=wml.replace('#ifdef MULTIPLAYER','#ifdef STORY_TEST_CAMPAIGN').replace('[multiplayer]','[scenario]').replace('[/multiplayer]','[/scenario]')
 metadata='[campaign]\nid=Two_Brothers\nname="Story checkpoint fixture"\nfirst_scenario=01_Rooting_Out_a_Mage\ndefine=STORY_TEST_CAMPAIGN\nrank=1\n[/campaign]\n'
 (data/'data/campaigns/Two_Brothers/_main.cfg').write_text(metadata+wml)
 userdata=root/('userdata-'+variant)
 text=cmd('story-real-play-'+variant,[engine,data,'--userdata-dir',userdata,'--campaign','Two_Brothers','--campaign-difficulty','1','--nogui','--nosound','--no-log-to-file','--log-strict','error','--log-none=audio','--plugin',plugin],env)
 assert 'STORY LIBERTY STORED AWARDS VERIFIED' in text, 'reviewed stored-unit rewards did not execute'
 record=next(profile.rglob('*.json'));before=json.loads(record.read_text());assert len(before['pending'])==1,before
 saves=list((userdata/'sync/saves').glob('Story-*.gz'));assert len(saves)==1,saves
 assert b'a'*64 not in gzip.decompress(saves[0].read_bytes())
 cmd('story-verify-'+variant,[engine,'--verify-story',variant],env)
 if variant=='win':
  autos=list((userdata/'sync/saves').glob('StoryMid.gz'));assert len(autos)==1,autos
  expected=record.read_bytes()
  reloaded=cmd('story-reload-duplicate',[engine,data,'--userdata-dir',userdata,'--load',autos[0].name,'--nogui','--nosound','--no-log-to-file','--log-strict','error','--log-none=audio','--plugin',reload_plugin],env)
  assert 'STORY COMBAT SCRIPT ADVANCEMENT VERIFIED' in reloaded, 'snapshot was not actually replayed'
  assert expected==record.read_bytes(),'old save duplicated checkpoint'
  original_save=gzip.decompress(autos[0].read_bytes())
  for label,old,new in [('account','30000000-0000-4000-8000-000000000001','30000000-0000-4000-8000-000000000002'),('generation','40000000-0000-4000-8000-000000000001','40000000-0000-4000-8000-000000000002')]:
   assert old.encode() in original_save
   altered=autos[0].parent/('Wrong-'+label+'.gz');altered.write_bytes(gzip.compress(original_save.replace(old.encode(),new.encode())))
   rejected=cmd('story-wrong-'+label,[engine,data,'--userdata-dir',userdata,'--load',altered.name,'--nogui','--nosound','--no-log-to-file','--log-strict','error','--log-none=audio','--plugin',reload_plugin],env,allowed=(0,1))
   assert '[story-account]' in rejected, 'foreign save did not reach the account binding gate'
   assert 'STORY COMBAT SCRIPT ADVANCEMENT VERIFIED' not in rejected
   assert expected==record.read_bytes(),'foreign save changed private checkpoints'
 if variant=='win':cmd('story-branch',[engine,'--verify-branch'],env)
 results.append({'variant':variant,'outcome':before['pending'][0]['outcome'],'heroes':before['pending'][0]['heroes'],'replay_sha256':hashlib.sha256(saves[0].read_bytes()).hexdigest()})
(root/'story-validation.json').write_text(json.dumps({'status':'passed','scope':'actual native story campaign/combat/XP/advancement/replay/durable retry; HTTP stub only','cases':results},indent=2))
print('ACTUAL STORY CAMPAIGN CHECKS PASSED',flush=True)
